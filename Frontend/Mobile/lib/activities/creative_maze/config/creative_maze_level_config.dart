  final double ballRadius;

  const CreativeMazeLevelConfig({
    required this.levelId,
    required this.startPoint,
    required this.endPoint,
    required this.endPointRadius,
    required this.wallRects,
    this.coinPositions = const [],
    this.ballRadius = 5,
  });
}
