/// Per-level maze geometry for Creative Maze.
///
/// All coordinates are NORMALISED (0.0–1.0) relative to the rendered maze
/// image, so they scale to any screen size. There are NO holes in Creative
/// Maze (unlike Bodily Maze) — the only outcome is reaching the end point.
///
/// Fill [creativeMazeConfigs] per level using the coordinate picker tool,
/// keyed by the level's backend id.
class CreativeMazeLevelConfig {
  final int levelId;
  final Offset startPoint; // normalized 0.0–1.0
  final Offset endPoint; // normalized 0.0–1.0
  final double endPointRadius; // normalized
  final List<Rect> wallRects; // normalized 0.0–1.0

  /// Positions of coin pickups on the maze, normalized 0.0–1.0.
  /// Each coin gives +1 to the collected count when the ball touches it.
